-- ==============================================================================
-- 01_setup_database_and_roles.sql
-- RetailPulse Cloud Data Warehouse Foundation Setup (Snowflake)
-- ==============================================================================

USE ROLE ACCOUNTADMIN;

-- 1. Create Functional Roles
CREATE ROLE IF NOT EXISTS RETAILPULSE_ADMIN_ROLE;
CREATE ROLE IF NOT EXISTS RETAILPULSE_AIRFLOW_ROLE;
CREATE ROLE IF NOT EXISTS RETAILPULSE_DBT_ROLE;
CREATE ROLE IF NOT EXISTS RETAILPULSE_BI_ROLE;

-- Hierarchy Grants
GRANT ROLE RETAILPULSE_AIRFLOW_ROLE TO ROLE RETAILPULSE_ADMIN_ROLE;
GRANT ROLE RETAILPULSE_DBT_ROLE     TO ROLE RETAILPULSE_ADMIN_ROLE;
GRANT ROLE RETAILPULSE_ADMIN_ROLE   TO ROLE SYSADMIN;

-- 2. Create Sized Compute Warehouses with Aggressive Auto-Suspend for Cost Control
CREATE WAREHOUSE IF NOT EXISTS RETAILPULSE_INGEST_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 1
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Dedicated warehouse for S3 COPY INTO and batch ingestion tasks';

CREATE WAREHOUSE IF NOT EXISTS RETAILPULSE_TRANSFORM_WH
    WITH WAREHOUSE_SIZE = 'SMALL'
    AUTO_SUSPEND = 120
    AUTO_RESUME = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 2
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Dedicated multi-cluster warehouse for dbt models and transformations';

CREATE WAREHOUSE IF NOT EXISTS RETAILPULSE_BI_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Dedicated read warehouse for Metabase / Superset / Tableau dashboards';

-- 3. Create Database & Layered Schemas
CREATE DATABASE IF NOT EXISTS RETAILPULSE_DW;
USE DATABASE RETAILPULSE_DW;

-- Architecture Schemas
CREATE SCHEMA IF NOT EXISTS RAW           COMMENT = 'Immutable append-only landing layer populated from S3';
CREATE SCHEMA IF NOT EXISTS STAGING       COMMENT = 'Views and light cleaning on top of raw tables';
CREATE SCHEMA IF NOT EXISTS INTERMEDIATE  COMMENT = 'Business logic, joins, and entity resolution models';
CREATE SCHEMA IF NOT EXISTS MARTS         COMMENT = 'Dimensional star schema for analytics (facts & dims)';
CREATE SCHEMA IF NOT EXISTS ETL_METADATA  COMMENT = 'High-watermark control tables, audit logs, and DLQ tracking';

-- 4. Role Privileges
GRANT USAGE ON WAREHOUSE RETAILPULSE_INGEST_WH    TO ROLE RETAILPULSE_AIRFLOW_ROLE;
GRANT USAGE ON WAREHOUSE RETAILPULSE_TRANSFORM_WH TO ROLE RETAILPULSE_DBT_ROLE;
GRANT USAGE ON WAREHOUSE RETAILPULSE_BI_WH        TO ROLE RETAILPULSE_BI_ROLE;

GRANT USAGE, CREATE SCHEMA ON DATABASE RETAILPULSE_DW TO ROLE RETAILPULSE_ADMIN_ROLE;
GRANT USAGE ON DATABASE RETAILPULSE_DW TO ROLE RETAILPULSE_AIRFLOW_ROLE;
GRANT USAGE ON DATABASE RETAILPULSE_DW TO ROLE RETAILPULSE_DBT_ROLE;
GRANT USAGE ON DATABASE RETAILPULSE_DW TO ROLE RETAILPULSE_BI_ROLE;

-- RAW & ETL_METADATA Access for Airflow
GRANT ALL PRIVILEGES ON SCHEMA RETAILPULSE_DW.RAW          TO ROLE RETAILPULSE_AIRFLOW_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA RETAILPULSE_DW.ETL_METADATA  TO ROLE RETAILPULSE_AIRFLOW_ROLE;

-- Transform access for dbt
GRANT ALL PRIVILEGES ON SCHEMA RETAILPULSE_DW.STAGING      TO ROLE RETAILPULSE_DBT_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA RETAILPULSE_DW.INTERMEDIATE  TO ROLE RETAILPULSE_DBT_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA RETAILPULSE_DW.MARTS        TO ROLE RETAILPULSE_DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAILPULSE_DW.RAW    TO ROLE RETAILPULSE_DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAILPULSE_DW.RAW TO ROLE RETAILPULSE_DBT_ROLE;

-- BI Read Access
GRANT USAGE ON SCHEMA RETAILPULSE_DW.MARTS TO ROLE RETAILPULSE_BI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAILPULSE_DW.MARTS TO ROLE RETAILPULSE_BI_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAILPULSE_DW.MARTS TO ROLE RETAILPULSE_BI_ROLE;
